"""FFmpeg audio: placeholder music beds, the final mix (ducked music + voice, -14 LUFS) and probing."""

from __future__ import annotations

import json
import subprocess
from pathlib import Path


class FFmpegError(RuntimeError):
    pass


def run(cmd: list[str]) -> str:
    p = subprocess.run(cmd, capture_output=True, text=True)
    if p.returncode != 0:
        raise FFmpegError(f"{' '.join(cmd[:3])} ... failed:\n{p.stderr[-1500:]}")
    return p.stdout


def probe(path: Path) -> dict:
    out = run(["ffprobe", "-v", "error", "-print_format", "json", "-show_format", "-show_streams", str(path)])
    return json.loads(out)


def duration_sec(path: Path) -> float:
    return float(probe(path)["format"]["duration"])


# Two synthetic ambient pads so the mix works out of the box. They are generated by this repo,
# so no third-party licence applies. Replace them with licensed tracks you prefer.
_BEDS = {
    "bed_a.mp3": "0.20*sin(2*PI*110*t)+0.14*sin(2*PI*164.81*t)+0.12*sin(2*PI*220*t)+0.10*sin(2*PI*277.18*t)",
    "bed_b.mp3": "0.20*sin(2*PI*98*t)+0.14*sin(2*PI*146.83*t)+0.12*sin(2*PI*196*t)+0.10*sin(2*PI*246.94*t)",
}


def generate_beds(out_dir: Path, seconds: int = 150, force: bool = False) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    made: list[Path] = []
    for name, expr in _BEDS.items():
        path = out_dir / name
        if path.exists() and not force:
            made.append(path)
            continue
        run(
            [
                "ffmpeg",
                "-y",
                "-loglevel",
                "error",
                "-f",
                "lavfi",
                "-i",
                f"aevalsrc={expr}:s=44100:d={seconds}",
                "-af",
                f"lowpass=f=900,tremolo=f=0.18:d=0.35,afade=t=in:d=3,afade=t=out:st={seconds - 3}:d=3",
                "-c:a",
                "libmp3lame",
                "-b:a",
                "128k",
                str(path),
            ]
        )
        made.append(path)
    return made


def mix_final(
    video: Path, narration: Path, out: Path, music: Path | None, music_volume: float = 0.22
) -> None:
    """Mux Remotion's silent video with narration plus a music bed ducked under the voice, normalised to
    -14 LUFS, web-safe (H.264 + AAC, faststart)."""
    out.parent.mkdir(parents=True, exist_ok=True)
    cmd = ["ffmpeg", "-y", "-loglevel", "error", "-i", str(video), "-i", str(narration)]
    if music is not None and music.exists():
        cmd += ["-stream_loop", "-1", "-i", str(music)]
        flt = (
            f"[1:a]asplit=2[voice][sc];[2:a]volume={music_volume}[m];"
            "[m][sc]sidechaincompress=threshold=0.05:ratio=8:attack=20:release=400[duck];"
            "[voice][duck]amix=inputs=2:duration=first:normalize=0,loudnorm=I=-14:TP=-1.5:LRA=11[a]"
        )
    else:
        flt = "[1:a]loudnorm=I=-14:TP=-1.5:LRA=11[a]"
    cmd += [
        "-filter_complex",
        flt,
        "-map",
        "0:v",
        "-map",
        "[a]",
        "-c:v",
        "copy",
        "-c:a",
        "aac",
        "-b:a",
        "192k",
        "-ac",
        "2",
        "-ar",
        "48000",
        "-movflags",
        "+faststart",
        "-shortest",
        str(out),
    ]
    run(cmd)
